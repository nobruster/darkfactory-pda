"""Executable byte-for-byte contract tests for Type 03 DataGen."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from checksum import sha256_hex
from generation import generate


ROOT = Path(__file__).resolve().parents[3]
CONTRACTS = ROOT / "contracts" / "types"
MAIN = CONTRACTS / "03-payment-slip-settlement" / "main"
CANONICAL = {
    "valid-minimal": (
        "valid-minimal.rem",
        "e1fc88f1363b1dd2dd44ed8c0389991"
        "a88d6aa4be71008d8a360e750b8e8d243",
    ),
    "valid-boundary": (
        "valid-boundary.rem",
        "59c7d152fa627ab3689d7d1b3b3e439e4"
        "c3e723b7b6759db1bfc7be731e86dc8",
    ),
    "malformed": (
        "malformed.rem",
        "327e6a24665ab48bc7d7130dddf389baa"
        "abf990d077db5a905284ec814048de1",
    ),
    "multi-lot": (
        "multi-lot.rem",
        "b0738ac5d795319c53f9b2ab9eec136f"
        "99162ca6a8a59ea1af35e424c72ef83a",
    ),
    "DF-SOURCE-003": (
        "df-source-003.rem",
        "25f36326988699045755164c65be92c77"
        "df3bbf5f2c2ac8afd7289d666025505",
    ),
}


class Type03ContractTest(unittest.TestCase):
    """Prove generated bytes equal independently approved fixtures."""

    def test_all_five_scenarios_match_pinned_raw_bytes(self) -> None:
        for scenario, (filename, expected_hash) in CANONICAL.items():
            with self.subTest(scenario=scenario):
                with tempfile.TemporaryDirectory() as output:
                    bundle = generate(
                        type_number="03",
                        scenario=scenario,
                        output_root=Path(output),
                        contracts_root=CONTRACTS,
                    )
                    actual = bundle.raw_file.read_bytes()
                    expected = (MAIN / filename).read_bytes()
                    if actual != expected:
                        mismatch = next(
                            (
                                offset
                                for offset, pair in enumerate(
                                    zip(actual, expected, strict=False)
                                )
                                if pair[0] != pair[1]
                            ),
                            min(len(actual), len(expected)),
                        )
                        self.fail(
                            "Type 03 raw bytes differ without disclosure: "
                            f"scenario={scenario}, "
                            f"actual_sha256={sha256_hex(actual)}, "
                            f"expected_sha256={sha256_hex(expected)}, "
                            f"first_mismatch_offset={mismatch}"
                        )
                    self.assertEqual(sha256_hex(actual), expected_hash)

    def test_transport_is_exact_ascii_240_byte_crlf_records(self) -> None:
        for scenario in CANONICAL:
            with self.subTest(scenario=scenario):
                with tempfile.TemporaryDirectory() as output:
                    bundle = generate(
                        type_number="03",
                        scenario=scenario,
                        output_root=Path(output),
                        contracts_root=CONTRACTS,
                    )
                    raw = bundle.raw_file.read_bytes()
                    raw.decode("ascii", errors="strict")
                    self.assertTrue(raw.endswith(b"\r\n"))
                    self.assertNotIn(b"\r\n\r\n", raw)
                    records = raw[:-2].split(b"\r\n")
                    self.assertTrue(records)
                    self.assertTrue(
                        all(len(record) == 240 for record in records)
                    )
                    self.assertEqual(len(raw), len(records) * 242)


if __name__ == "__main__":
    unittest.main()
