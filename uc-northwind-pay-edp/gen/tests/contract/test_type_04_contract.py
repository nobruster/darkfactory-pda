"""Executable byte-for-byte contract tests for Type 04 DataGen."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from checksum import sha256_hex
from generation import generate


ROOT = Path(__file__).resolve().parents[3]
CONTRACTS = ROOT / "contracts" / "types"
MAIN = CONTRACTS / "04-ted-transfer-settlement" / "main"
CANONICAL = {
    "valid-minimal": (
        "valid-minimal.dat",
        "f853e3a48cc7e2b4741f4651596b9ff28"
        "346b5a4b0ecec44abc80e7595af3c87",
    ),
    "valid-boundary": (
        "valid-boundary.dat",
        "7d09630e3c70c497786cd3aa9b885b75b"
        "92c951b94fad652ec6764b9c26f5ab7",
    ),
    "malformed": (
        "malformed.dat",
        "3387ce34995f5c07c25423e5737fc5808"
        "d8ec18f050f97b3680386a48ceb2c91",
    ),
    "all-returned-zero-net": (
        "all-returned-zero-net.dat",
        "ae868704360982a462d602545770f1d421"
        "9accc987883982e79d16dad1da8452",
    ),
    "DF-SOURCE-004": (
        "df-source-004.dat",
        "2668b4b6d757a3a0a52aaf1b30a0ff54"
        "21630b3e49f5e4fd823e5eef7162f333",
    ),
}
RECORD_LENGTHS = {
    b"H": 56,
    b"D": 162,
    b"R": 91,
    b"T": 82,
}


class Type04ContractTest(unittest.TestCase):
    """Prove generated bytes equal independently approved fixtures."""

    def test_all_five_scenarios_match_pinned_raw_bytes(self) -> None:
        for scenario, (filename, expected_hash) in CANONICAL.items():
            with self.subTest(scenario=scenario):
                with tempfile.TemporaryDirectory() as output:
                    bundle = generate(
                        type_number="04",
                        scenario=scenario,
                        output_root=Path(output),
                        contracts_root=CONTRACTS,
                    )
                    actual = bundle.raw_file.read_bytes()
                    expected = (MAIN / filename).read_bytes()
                    if actual != expected:
                        mismatch = next(
                            (
                                offset
                                for offset, pair in enumerate(
                                    zip(actual, expected, strict=False)
                                )
                                if pair[0] != pair[1]
                            ),
                            min(len(actual), len(expected)),
                        )
                        self.fail(
                            "Type 04 raw bytes differ without disclosure: "
                            f"scenario={scenario}, "
                            f"actual_sha256={sha256_hex(actual)}, "
                            f"expected_sha256={sha256_hex(expected)}, "
                            f"first_mismatch_offset={mismatch}"
                        )
                    self.assertEqual(sha256_hex(actual), expected_hash)

    def test_transport_and_deliberate_bare_lf_are_exact(self) -> None:
        for scenario in CANONICAL:
            with self.subTest(scenario=scenario):
                with tempfile.TemporaryDirectory() as output:
                    raw = generate(
                        type_number="04",
                        scenario=scenario,
                        output_root=Path(output),
                        contracts_root=CONTRACTS,
                    ).raw_file.read_bytes()
                    raw.decode("ascii", errors="strict")
                    if scenario == "malformed":
                        self.assertEqual(
                            raw.count(b"\n") - raw.count(b"\r\n"),
                            1,
                        )
                        raw = raw.replace(b"\n", b"\r\n", 1)
                    else:
                        self.assertEqual(
                            raw.count(b"\n"),
                            raw.count(b"\r\n"),
                        )
                    self.assertTrue(raw.endswith(b"\r\n"))
                    records = raw[:-2].split(b"\r\n")
                    self.assertTrue(records)
                    self.assertTrue(
                        all(
                            len(record)
                            == RECORD_LENGTHS.get(record[:1], -1)
                            for record in records
                        )
                    )


if __name__ == "__main__":
    unittest.main()
